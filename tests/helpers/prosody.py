"""Credentials and endpoint details for disposable Prosody fixtures."""

from __future__ import annotations

import re
import subprocess
from pathlib import Path
from xml.etree import ElementTree  # nosec B405 # Locally generated outgoing SDK XML.

PROSODY_DOMAIN = "xmpp.lab.test"
_MUC_DOMAIN = "rooms.xmpp.lab.test"


class ProsodyEnvironment:
    """Holds connection details and per-run private accounts for Prosody.

    Account passwords are generated per session with ``secrets`` and live
    only in this object; they are never written to config snapshots,
    artifacts, or logs.
    """

    def __init__(
        self,
        container_name: str,
        host: str,
        port: int,
        config_dir: Path,
        ca_path: Path,
        image: str,
    ) -> None:
        self.container_name = container_name
        self.host = host
        self.port = port
        self.config_dir = config_dir
        self.ca_path = ca_path
        self.image = image
        self.domain = PROSODY_DOMAIN
        self.muc_domain = _MUC_DOMAIN
        self._accounts: dict[str, str] = {}

    def register_account(self, localpart: str, password: str) -> None:
        """Record one account provisioned through prosodyctl."""
        self._accounts[localpart] = password

    def jid(self, localpart: str) -> str:
        return f"{localpart}@{self.domain}"

    def password(self, localpart: str) -> str:
        return self._accounts[localpart]

    def room_jid(self, room: str) -> str:
        return f"{room}@{self.muc_domain}"


def generate_prosody_certs(config_dir: Path) -> Path:
    """Create a throwaway CA and server certificate for the fixture."""
    san = (
        "subjectAltName=DNS:xmpp.lab.test,DNS:rooms.xmpp.lab.test,"
        "DNS:localhost,IP:127.0.0.1"
    )
    subprocess.run(
        [
            "openssl",
            "req",
            "-x509",
            "-newkey",
            "rsa:2048",
            "-sha256",
            "-days",
            "3",
            "-nodes",
            "-keyout",
            str(config_dir / "ca.key"),
            "-out",
            str(config_dir / "ca.crt"),
            "-subj",
            "/CN=medre-prosody-fixture-ca",
            # OpenSSL verification refuses a CA without an explicit key usage.
            "-addext",
            "basicConstraints=critical,CA:TRUE",
            "-addext",
            "keyUsage=critical,keyCertSign,cRLSign",
        ],
        check=True,
        capture_output=True,
        timeout=60,
    )
    subprocess.run(
        [
            "openssl",
            "req",
            "-newkey",
            "rsa:2048",
            "-sha256",
            "-nodes",
            "-keyout",
            str(config_dir / "server.key"),
            "-out",
            str(config_dir / "server.csr"),
            "-subj",
            "/CN=xmpp.lab.test",
            "-addext",
            san,
        ],
        check=True,
        capture_output=True,
        timeout=60,
    )
    ext_file = config_dir / "server.ext"
    ext_file.write_text(san + "\n")
    subprocess.run(
        [
            "openssl",
            "x509",
            "-req",
            "-in",
            str(config_dir / "server.csr"),
            "-CA",
            str(config_dir / "ca.crt"),
            "-CAkey",
            str(config_dir / "ca.key"),
            "-CAcreateserial",
            "-days",
            "3",
            "-sha256",
            "-out",
            str(config_dir / "server.crt"),
            "-extfile",
            str(ext_file),
        ],
        check=True,
        capture_output=True,
        timeout=60,
    )
    # The container runs Prosody as its own unprivileged user; the key must
    # be readable through the read-only bind mount. This is a per-run
    # throwaway key that is deleted with the config directory.
    config_dir.joinpath("server.key").chmod(0o644)
    return config_dir / "ca.crt"


def groupchat_write(raw: str | bytes) -> dict[str, str | None] | None:
    """Decode one locally generated Slixmpp stanza at the send_raw boundary.

    Do not substitute the intended send payload for the actual destination or
    body. This helper only accepts the SDK's complete serialized message;
    malformed message XML is a qualification failure, not an absent write.
    """
    if isinstance(raw, bytes):
        raw = raw.decode("utf-8")
    if re.match(r"<(?:[A-Za-z_][\w.-]*:)?message(?=[\s/>])", raw.lstrip()) is None:
        return None
    # The XML is generated by the local pinned SDK, not received from peers.
    try:
        stanza = ElementTree.fromstring(raw)  # nosec B314
    except ElementTree.ParseError as exc:
        raise ValueError("malformed serialized XMPP message") from exc
    if (
        stanza.tag not in ("message", "{jabber:client}message")
        or stanza.get("type") != "groupchat"
    ):
        return None
    namespace = stanza.tag.removesuffix("message")
    body = stanza.find(f"{namespace}body")
    origin = stanza.find("{urn:xmpp:sid:0}origin-id")
    return {
        "to": stanza.get("to"),
        "body": body.text if body is not None else None,
        "origin_id": origin.get("id") if origin is not None else None,
        "native_id": None,
    }
