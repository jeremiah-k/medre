"""Replay CLI command: execute replay operations via the built runtime.

Modes without delivery side effects (everything except ``best_effort``)
run against the built-but-not-started runtime with read-only storage
access.  ``best_effort`` re-delivers through real adapters, so it starts
the runtime in the replay-delivery scope first (storage → pipeline →
adapters; the durable-ingress and retry workers stay stopped so the
replay never dispatches unrelated pending/live work) and stops it
afterwards.
"""

from __future__ import annotations

import asyncio
import json
import logging
import sys
import time as _time
from typing import Any

from medre.config.env import apply_env_overrides
from medre.config.loader import load_config
from medre.core.delivery_authority import DeliveryIdentity
from medre.core.engine.replay.summary import collect_replay_summary
from medre.core.engine.replay.types import ReplayMode, ReplayRequest
from medre.core.observability.exact_target import ExactTargetSelection
from medre.core.observability.sanitization import sanitize_error
from medre.core.supervision.diagnostic_contract import (
    PENDING_DELIVERY_COUNT,
    QUEUE_PENDING,
)
from medre.runtime.app import StartupScope
from medre.runtime.builder import RuntimeBuilder

from .exit_codes import EXIT_BUILD, EXIT_CONFIG, EXIT_STARTUP
from .json import to_json

_logger = logging.getLogger(__name__)

_BEST_EFFORT_WARNING = (
    "WARNING: BEST_EFFORT replay sends real messages. A non-empty run ID "
    "atomically claims one target generation in durable storage, but "
    "duplicate-send risk remains for prior live delivery, different/empty "
    "run IDs, and ambiguous transport retry/recovery. Use --mode dry_run first "
    "to preview."
)

#: Components in the canonical delivery plan id generated by
#: :func:`medre.core.planning.delivery_plan.stable_delivery_plan_id`:
#: ``plan:{event_id}:{route_id}:{index}:{hash}``.
_PLAN_ID_COMPONENTS = 5

#: Minimum ``--exact-target`` components after the event for a value to be
#: readable as a colon-bearing plan id: the five plan components plus the
#: adapter (the channel tail is optional).
_PLAN_FORM_MIN_COMPONENTS = _PLAN_ID_COMPONENTS + 1

#: Length and alphabet of the SHA-256 target-hash tail inside a canonical
#: plan id (``hexdigest()[:16]`` — sixteen lowercase hex characters).
_TARGET_HASH_LENGTH = 16
_TARGET_HASH_DIGITS = frozenset("0123456789abcdef")


def _is_target_hash(component: str) -> bool:
    """Whether one component matches the canonical plan id's hash tail."""
    return len(component) == _TARGET_HASH_LENGTH and set(component) <= (
        _TARGET_HASH_DIGITS
    )


def _split_identity_spec(
    spec: str, *, no_channel: bool
) -> tuple[str, str, str, str | None]:
    """Split one ``EVENT:PLAN:ADAPTER[:CHANNEL]`` value into identity fields.

    Colon-free plan ids keep the historical left-to-right split: the plan is
    the second colon-separated component and the channel is everything after
    the third colon, so colon-bearing channels such as Matrix rooms stay
    intact. A colon-bearing plan id — every persisted plan carries the
    canonical ``plan:{event}:{route}:{index}:{hash}`` shape — is detected by
    its ``plan:`` prefix and consumed as exactly five components, so the
    sixth component is the adapter and the channel keeps its right-anchored
    tail.

    Detection is conservative: a value that cannot be a canonical plan id
    (too few components, or a blank interior where the plan's embedded event
    would sit) falls back to the historical split, so no component is ever
    silently reattributed. A hash-tailed plan id that embeds a different
    event than the named one is a selection mistake, so it fails loudly
    instead of parsing into an identity no persisted row can carry.
    """
    event, first_colon, remainder = spec.partition(":")
    components = remainder.split(":") if first_colon else []
    plan_form = (
        bool(first_colon)
        and bool(event.strip())
        and remainder.startswith("plan:")
        and len(components) >= _PLAN_FORM_MIN_COMPONENTS
        and bool(components[1].strip())
    )
    if plan_form and components[1] == event:
        if any(not part.strip() for part in components[:_PLAN_FORM_MIN_COMPONENTS]):
            raise ValueError("event, plan and adapter must be nonblank")
        channel: str | None = (
            ":".join(components[_PLAN_ID_COMPONENTS + 1 :])
            if len(components) > _PLAN_FORM_MIN_COMPONENTS
            else None
        )
        if no_channel and channel is not None:
            raise ValueError(
                "expected exactly EVENT:PLAN:ADAPTER; a channel-bearing"
                " identity cannot select no channel"
            )
        return (
            event,
            ":".join(components[:_PLAN_ID_COMPONENTS]),
            components[_PLAN_ID_COMPONENTS],
            channel,
        )
    if plan_form and _is_target_hash(components[4]):
        raise ValueError(
            f"the plan id embeds event {components[1]!r}, not {event!r};"
            " name the event the plan id belongs to"
        )
    # Historical split for colon-free plan ids.
    parts = spec.split(":", 3)
    if no_channel and len(parts) != 3:
        raise ValueError(
            "expected exactly EVENT:PLAN:ADAPTER; a channel-bearing identity"
            " cannot select no channel"
        )
    if len(parts) < 3:
        raise ValueError("expected EVENT:PLAN:ADAPTER or EVENT:PLAN:ADAPTER:CHANNEL")
    return event, parts[1], parts[2], None if len(parts) == 3 else parts[3]


#: The ``--exact-target-json`` value shape, stated for error messages: a
#: JSON array of exactly four elements, the last a string or ``null``.
_JSON_IDENTITY_SHAPE = (
    "expected a JSON array of four nonblank strings"
    " [EVENT, TARGET, ADAPTER, CHANNEL|null]"
)


def _parse_json_identity_spec(value: str) -> tuple[str, str, str, str | None]:
    """Decode one ``--exact-target-json`` value into identity fields.

    The JSON form is the explicit grammar for colon-bearing identifiers:
    ``["EVENT", "TARGET", "ADAPTER", "CHANNEL-or-null"]`` is positional and
    unambiguous, so a colon-bearing event id, a canonical colon-bearing
    plan id (``plan:{event}:{route}:{index}:{hash}``), and a colon-bearing
    channel all survive byte-exact. The compact colon spelling cannot make
    that distinction from the overloaded string alone — a legacy identity
    whose plan component is literally ``plan`` next to a colon-bearing
    channel is byte-identical to the canonical plan-id spelling — which is
    exactly why this form exists. Validation is strict: the value must be
    valid JSON, an array, exactly four elements, the first three nonblank
    strings, and the fourth a nonblank string or ``null`` (``null`` is the
    no-channel spelling). Any violation raises :class:`ValueError`, which
    the caller maps to the same configuration-error exit as the compact
    form's malformed specs.
    """
    try:
        decoded = json.loads(value)
    except ValueError as exc:
        raise ValueError(f"{_JSON_IDENTITY_SHAPE}: invalid JSON") from exc
    if not isinstance(decoded, list):
        raise ValueError(_JSON_IDENTITY_SHAPE)
    if len(decoded) != 4:
        raise ValueError(f"{_JSON_IDENTITY_SHAPE}; got {len(decoded)} element(s)")
    event, target, adapter, channel = decoded
    for name, element in (
        ("EVENT", event),
        ("TARGET", target),
        ("ADAPTER", adapter),
    ):
        if not isinstance(element, str) or not element.strip():
            raise ValueError(
                f"{_JSON_IDENTITY_SHAPE}: {name} must be a nonblank string"
            )
    if channel is not None and (not isinstance(channel, str) or not channel.strip()):
        raise ValueError(
            f"{_JSON_IDENTITY_SHAPE}: CHANNEL must be a nonblank string or" " null"
        )
    return event, target, adapter, channel


def _parse_exact_target_specs(
    exact_targets: list[str] | None,
    exact_no_channel: list[str] | None,
    exact_target_json: list[str] | None = None,
) -> tuple[ExactTargetSelection, ...]:
    """Parse repeatable exact-target values into delivery selections.

    Compact syntax: ``--exact-target EVENT:PLAN:ADAPTER`` names the
    deliberate no-channel identity and ``--exact-target
    EVENT:PLAN:ADAPTER:CHANNEL`` names one channel. The plan component may
    itself contain colons: a canonical ``plan:{event}:{route}:{index}:{hash}``
    plan id is consumed as one five-component plan, so the event is anchored
    before it and the adapter and channel tail after it. Colon-free plan ids
    keep the historical three-colon split. ``--exact-no-channel
    EVENT:PLAN:ADAPTER`` is the explicit spelling of the three-component form
    and accepts exactly three components (or a colon-bearing plan id with no
    channel tail).

    Explicit JSON syntax: ``--exact-target-json
    '["EVENT","TARGET","ADAPTER","CHANNEL-or-null"]'`` names the four identity
    fields positionally, so colon-bearing event ids, plan ids, and channels
    are all expressed without the compact form's shape detection. ``null`` is
    the no-channel spelling.

    A blank channel component is rejected: persistence would normalize it to
    the no-channel identity and silently widen the selection. Each flag is
    repeatable and selections accumulate; one delivery identity may not
    repeat across all three flags.
    """
    selections: list[ExactTargetSelection] = []
    seen: set[DeliveryIdentity] = set()

    def add(
        event: str,
        plan: str,
        adapter: str,
        channel: str | None,
        *,
        flag: str,
        spec: str,
    ) -> None:
        if any(not part.strip() for part in (event, plan, adapter)):
            raise ValueError(
                f"Invalid {flag} {spec!r}: event, plan and adapter must be" " nonblank"
            )
        if channel is not None and not channel.strip():
            raise ValueError(
                f"Invalid {flag} {spec!r}: a blank string is not a channel"
                " decision; omit the ':CHANNEL' component or use"
                " --exact-no-channel"
            )
        try:
            selection = ExactTargetSelection(
                event_id=event,
                delivery_plan_id=plan,
                target_adapter=adapter,
                target_channel=channel,
            )
        except ValueError as exc:
            raise ValueError(f"Invalid {flag} {spec!r}: {exc}") from exc
        if selection.identity in seen:
            raise ValueError(
                f"Duplicate exact-target selection for one delivery"
                f" identity: {spec!r}"
            )
        seen.add(selection.identity)
        selections.append(selection)

    for spec in exact_targets or []:
        try:
            event, plan, adapter, channel = _split_identity_spec(spec, no_channel=False)
        except ValueError as exc:
            raise ValueError(f"Invalid --exact-target {spec!r}: {exc}") from exc
        add(event, plan, adapter, channel, flag="--exact-target", spec=spec)
    for spec in exact_no_channel or []:
        try:
            event, plan, adapter, channel = _split_identity_spec(spec, no_channel=True)
        except ValueError as exc:
            raise ValueError(f"Invalid --exact-no-channel {spec!r}: {exc}") from exc
        add(event, plan, adapter, channel, flag="--exact-no-channel", spec=spec)
    for value in exact_target_json or []:
        try:
            event, plan, adapter, channel = _parse_json_identity_spec(value)
        except ValueError as exc:
            raise ValueError(f"Invalid --exact-target-json {value!r}: {exc}") from exc
        add(event, plan, adapter, channel, flag="--exact-target-json", spec=value)
    return tuple(selections)


async def _drain_inflight_deliveries(app: Any, timeout: float) -> None:
    """Wait for adapters' in-flight outbound deliveries to go terminal.

    Reads each started adapter's own ``diagnostics()`` report and waits
    while an adapter still reports unflushed outbound work under the
    shared keys from :mod:`medre.core.supervision.diagnostic_contract`
    (``session.pending_delivery_count`` for async-transfer adapters such
    as LXMF; ``queue_pending`` for queue-backed adapters such as
    Meshtastic).  Returns as soon as every exposed count is zero, or
    after *timeout* seconds.  Purely observational: no adapter state is
    mutated, and the lifecycle stop remains the teardown authority.
    """
    deadline = _time.monotonic() + timeout
    while True:
        any_exposed = False
        all_terminal = True
        for adapter_id in getattr(app, "started_adapter_ids", []):
            adapter = app.adapters.get(adapter_id)
            diag_fn = getattr(adapter, "diagnostics", None)
            if diag_fn is None:
                continue
            diag = diag_fn() or {}
            session = diag.get("session") or {}
            if PENDING_DELIVERY_COUNT in session:
                any_exposed = True
                if session[PENDING_DELIVERY_COUNT] > 0:
                    all_terminal = False
                    break
            queue_pending = diag.get(QUEUE_PENDING)
            if queue_pending is not None:
                any_exposed = True
                if queue_pending > 0:
                    all_terminal = False
                    break
        if not any_exposed or all_terminal:
            return
        if _time.monotonic() >= deadline:
            return
        await asyncio.sleep(0.2)


async def _teardown_replay_runtime(app: Any, drain_timeout: float) -> None:
    """Teardown after a ``best_effort`` replay body (runs from ``finally``).

    Preserves the replay body's own failure or cancellation as the
    operator-facing error: a secondary teardown failure (the bounded
    drain, ``app.stop()``) is logged and never allowed to replace the
    in-flight exception.  When the body succeeded, teardown failures
    still propagate so a broken shutdown is visible.  The drain and
    ``stop()`` share one ``shutdown_drain_timeout_seconds`` deadline —
    congestion cannot spend the documented drain budget twice
    (durable-ingress.md "Capacity and shutdown handoff").
    """
    primary_error = sys.exc_info()[1]
    drain_deadline = _time.monotonic() + drain_timeout
    drain_error: BaseException | None = None
    stop_error: BaseException | None = None
    # Give adapters' in-flight outbound deliveries a bounded window to
    # reach terminal state before teardown — an immediate stop would abort
    # asynchronous transfers (e.g. LXMF DIRECT link delivery) right after
    # acceptance.  Bounded by the documented shutdown drain limit; purely
    # observational: delivery truth is recorded only from typed adapter
    # feedback/provider observations through lifecycle authority, never from
    # aggregate drain state.
    try:
        await _drain_inflight_deliveries(
            app, max(0.0, drain_deadline - _time.monotonic())
        )
    except BaseException as exc:
        # The drain is observational only.  It must never prevent lifecycle
        # teardown, including when it is itself cancelled.  Preserve a replay
        # body's already-in-flight error; otherwise surface the drain failure
        # only after ``app.stop()`` has had its chance to close resources.
        if primary_error is None:
            drain_error = exc
            _logger.error("Replay pre-stop drain failed: %s", sanitize_error(str(exc)))
        else:
            _logger.warning(
                "Replay pre-stop drain failed (replay error preserved): %s",
                sanitize_error(str(exc)),
            )
    # Full lifecycle teardown (stops adapters, closes storage), bounded by
    # the SAME deadline the drain just consumed from.
    try:
        await app.stop(drain_deadline=drain_deadline)
    except BaseException as exc:
        if primary_error is None:
            stop_error = exc
        else:
            _logger.error(
                "Runtime stop after replay failure also failed "
                "(primary replay error preserved): %s",
                sanitize_error(str(exc)),
            )

    # When the replay body itself succeeded, teardown failures are fatal —
    # but only after the full lifecycle stop has been attempted.  Prefer the
    # stop failure because it describes the authoritative teardown operation;
    # chain an earlier observational drain failure for diagnosis.
    if primary_error is None and stop_error is not None:
        if drain_error is not None:
            raise stop_error from drain_error
        raise stop_error
    if primary_error is None and drain_error is not None:
        raise drain_error


async def _replay(
    config_path: str | None,
    mode: str,
    event_id: str | None,
    json_output: bool,
    target_adapters: list[str] | None,
    route_ids: list[str] | None,
    limit: int,
    run_id: str = "",
    exact_targets: list[str] | None = None,
    exact_no_channel: list[str] | None = None,
    exact_target_json: list[str] | None = None,
) -> None:
    """Execute a replay operation via the built (not started) runtime."""
    # Validate mode.
    mode_map = {m.value: m for m in ReplayMode}
    if mode not in mode_map:
        print(
            f"Error: invalid mode {mode!r}. "
            f"Valid modes: {', '.join(sorted(mode_map.keys()))}",
            file=sys.stderr,
        )
        sys.exit(EXIT_CONFIG)

    # Validate exact-target selections before touching any configuration:
    # malformed operator input is a config error, never a runtime failure.
    try:
        exact_selections = _parse_exact_target_specs(
            exact_targets, exact_no_channel, exact_target_json
        )
    except ValueError as exc:
        print(f"Error: {exc}", file=sys.stderr)
        sys.exit(EXIT_CONFIG)

    replay_mode = mode_map[mode]
    # Request construction validates the execution key and selection
    # identity before configuration loading or adapter startup.
    try:
        request = ReplayRequest(
            mode=replay_mode,
            correlation_ids=[event_id] if event_id else None,
            target_adapters=target_adapters,
            route_ids=tuple(route_ids) if route_ids else (),
            limit=limit,
            run_id=run_id,
            exact_target_selections=exact_selections,
        )
    except ValueError as exc:
        print(f"Error: invalid replay request: {exc}", file=sys.stderr)
        sys.exit(EXIT_CONFIG)

    # Warn for BEST_EFFORT.
    if replay_mode == ReplayMode.BEST_EFFORT and not json_output:
        print(_BEST_EFFORT_WARNING, file=sys.stderr)
        print(file=sys.stderr)

    # Load config and build runtime (but do NOT start it).
    try:
        config, _source, paths = load_config(config_path)
        # Env overrides share the config-error boundary (see run command).
        config = apply_env_overrides(config, paths)
    except Exception as exc:
        print(f"Config error: {exc}", file=sys.stderr)
        sys.exit(EXIT_CONFIG)

    builder = RuntimeBuilder(config, paths)
    try:
        app = builder.build()
    except Exception as exc:
        print(f"Runtime build error: {exc}", file=sys.stderr)
        sys.exit(EXIT_BUILD)

    if app.replay_engine is None:
        print(
            "Error: replay engine not available — runtime was built without one.",
            file=sys.stderr,
        )
        sys.exit(EXIT_BUILD)

    if app.storage is None:
        print(
            "Error: storage not available — runtime was built without one.",
            file=sys.stderr,
        )
        sys.exit(EXIT_BUILD)

    # Side-effect modes (best_effort) re-deliver through real adapters, so
    # the built runtime must be STARTED — the deliver stage requires live
    # adapters and fails with ``AdapterPermanentError("Adapter not
    # started")`` otherwise (observed on real hardware recovery).  Modes
    # without delivery side effects keep the read-only storage-only path.
    needs_runtime = replay_mode == ReplayMode.BEST_EFFORT
    if needs_runtime:
        try:
            # REPLAY scope: adapters start so the selected replay can be
            # delivered through them, but the durable-ingress and retry
            # workers stay stopped — the replay must not dispatch unrelated
            # pending/retryable work or route live ingress outside the
            # selected replay.  Ingress received while scoped crosses the
            # durable admission boundary and is processed by the next live
            # start (see StartupScope.REPLAY).
            await app.start(scope=StartupScope.REPLAY)
        except Exception as exc:
            print(
                f"\nRuntime startup failed: {sanitize_error(str(exc))}",
                file=sys.stderr,
                flush=True,
            )
            sys.exit(EXIT_STARTUP)
    else:
        # Initialize storage for read access without starting the runtime.
        await app.storage.initialize()
    try:
        # Execute replay.
        t0 = _time.monotonic()
        results = app.replay_engine.replay(request)
        summary = await collect_replay_summary(
            results,
            mode=replay_mode,
            elapsed_ms=(_time.monotonic() - t0) * 1000,
            run_id=request.run_id,
        )

        summary_dict = summary.to_dict()
    finally:
        if needs_runtime:
            # Preserve the replay body's failure/cancellation as the
            # operator-facing error; secondary drain/stop failures are
            # surfaced without replacing it.  Drain and stop share one
            # documented shutdown-drain deadline.
            await _teardown_replay_runtime(
                app, config.limits.shutdown_drain_timeout_seconds
            )
        else:
            await app.storage.close()

    if json_output:
        print(to_json(summary_dict))
    else:
        # Human-readable summary.
        print(f"Replay: {mode}")
        if request.run_id:
            print(f"  Run ID:        {request.run_id}")
        print(f"  Events scanned:  {summary.events_scanned}")
        print(f"  Events replayed: {summary.events_replayed}")
        print(f"  Passed:          {summary.by_status.get('passed', 0)}")
        print(f"  Skipped:         {summary.by_status.get('skipped', 0)}")
        if summary.skip_reasons:
            for reason, count in sorted(summary.skip_reasons.items()):
                print(f"    {reason}: {count}")
        print(f"  Failed:          {summary.by_status.get('failed', 0)}")
        print(f"  Errors:          {summary.by_status.get('error', 0)}")
        print(f"  Elapsed:         {summary.elapsed_ms:.1f}ms")
        if summary.errors:
            print(f"  Errors ({len(summary.errors)}):")
            for err in summary.errors[:10]:
                print(f"    {err[:120]}")
        if summary.by_route:
            print("  Per-route:")
            for rid, counts in sorted(summary.by_route.items()):
                print(
                    f"    {rid}: {counts['succeeded']} succeeded, "
                    f"{counts['failed']} failed"
                )
